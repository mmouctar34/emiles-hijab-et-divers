from harness import *
S = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out') + '/'
FIX = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fixtures') + '/'
e = Env()
ok = True
def check(name, cond, extra=''):
    global ok
    print(('PASS ' if cond else 'FAIL ') + name + (' ' + str(extra) if extra and not cond else ''))
    ok = ok and bool(cond)
def noover(p): return p.evaluate("document.documentElement.scrollWidth<=window.innerWidth+1")

c = e.ctx(w=390, h=844, mobile=True); p = e.page(c, edit=True)
load(p, hash='#gestion'); p.wait_for_timeout(400)
check('mobile: pas de débordement (liste)', noover(p), p.evaluate("document.documentElement.scrollWidth"))
p.screenshot(path=S+'m-admin.png')
p.evaluate("window.scrollTo(0,560)"); p.wait_for_timeout(150)
p.screenshot(path=S+'m-admin-rows.png')
p.evaluate("window.scrollTo(0,0)")
p.click('[data-adm=new]'); p.wait_for_selector('#editModal:not([hidden])'); p.wait_for_timeout(200)
p.screenshot(path=S+'m-editor-top.png')
check('mobile: éditeur plein écran', p.evaluate("(()=>{const r=document.querySelector('.ed-box').getBoundingClientRect();return r.width>=389&&r.height>=843})()"))
p.set_input_files('#edFile', FIX+'photo-big.jpg'); p.wait_for_selector('#edImg'); p.wait_for_timeout(200)
p.evaluate("document.querySelector('#ed-name').scrollIntoView({block:'start'})"); p.wait_for_timeout(100)
p.fill('#ed-name','Brume vanille 250 ml')
p.screenshot(path=S+'m-editor-photo.png')
p.evaluate("document.querySelector('#edPacks').scrollIntoView({block:'start'})"); p.wait_for_timeout(150)
p.fill('#pk-p-0','3000')
p.screenshot(path=S+'m-editor-packs.png')
check('mobile: pas de débordement (éditeur)', p.evaluate("(()=>{const b=document.querySelector('.ed-body');return b.scrollWidth<=b.clientWidth+1})()"))
p.click('[data-ed=save]'); p.wait_for_timeout(250)
p.screenshot(path=S+'m-editor-errors.png')
p.fill('#pk-p-1','6000'); p.fill('#pk-p-2','12000')
p.click('[data-ed=save]'); p.wait_for_timeout(300)
p.screenshot(path=S+'m-after-save.png')
p.click('#admSum [data-adm=publish]'); p.wait_for_selector('#sheet:not([hidden])'); p.wait_for_timeout(150)
p.screenshot(path=S+'m-sheet.png')
p.click('#sheetAct .btn >> nth=0')
p.evaluate("document.querySelector('#page-gestion [data-page=home]').click()"); p.wait_for_timeout(300)
p.evaluate("window.scrollTo(0, document.querySelector('#boutique').offsetTop)"); p.wait_for_timeout(200)
p.screenshot(path=S+'m-shop-draft.png')
check('mobile: pas de débordement (boutique)', noover(p))
check('erreurs js', not p.errors, p.errors)
c.close()

